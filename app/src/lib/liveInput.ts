/** 能"读回真实值"的那两类元素（`null` / `undefined` 也算，调用方常常在拿不到时退回旧值） */
export type LiveField = HTMLInputElement | HTMLTextAreaElement | null | undefined

/**
 * 从屏上那个元素读回真实值。
 *
 * @param el       提交路径上拿到的 DOM 节点（一般是 `ref.current`；拿不到就传 `null`）
 * @param fallback 拿不到元素时用的值（**必须是 state 那一份**，别编一个新值）
 *
 * ⚠️ 用 `typeof el.value === 'string'` 判，而不是只判 `el` 非空：
 *    某些宿主环境（老 WebView / 测试假 DOM）里的节点没有 `value`
 *    —— 那时退回 `fallback`，绝不会读出一个 `undefined` 当字符串用。
 */
export function liveValue(el: LiveField, fallback = ''): string {
  return el && typeof el.value === 'string' ? el.value : fallback
}
