/**
 * 更新日志（「我的 → 更新日志」那一屏的**唯一来源**）。
 *
 * ## 为什么从 `pages/Settings.tsx` 挪到这里
 *
 * 它原来是硬编码在设置页里的一个数组，而**发版三步的第③步就是"在它顶部加一段"**——
 * 版本号（`lib/version.ts` 的 `APP_VERSION`）和它分居两个文件，于是真的走散了：
 * 设置页「关于」里写着 v0.9.0，同一页下面的更新日志却停在 0.8.0，自己跟自己打架。
 * 现在发版 = **一个文件两处改**（`APP_VERSION` + 这里顶部加一段），第②步是 `app/package.json`。
 *
 * ## 写法上的纪律（写给老师看的，不是 changelog 生成器）
 *
 * - 🔴 **要短**（用户 2026-10-04 拍板："全部改简洁，不要写那么多，学一下其他正规产品的更新日志"）：
 *   每条**一行**，**以「新增 / 修复 / 优化」开头**，一句话说清老师能感觉到的那件事。
 *   一版 **3–6 条**为宜；写不下就说明该拆成两版了。
 *   详版（谁在哪天动的、为什么、踩了什么坑）**不在这屏** —— 它在交付目录的
 *   `01-教室端exe\更新日志.md` / `02-教师端exe\更新日志.md` / `03-教师端apk\更新日志.md`
 *   与仓库的 `施工进展台账.md` / `功能设计与不变量.md`。
 * - **只写教师能感觉到的那件事**：不写文件名、不写"重构""收口"这类内部词、
 *   不写内部编号（W16 / I8 这种只在 `功能设计与不变量.md` 里有意义）。
 * - 🔴 **只写"更新了什么功能"**（用户 2026-09-29 拍板）。以下这些**一律不写**：
 *   超管运维面板、账号隔离、拍照识别额度、移动端导航换色、
 *   自动化检查那一类**只对维护者有意义**的条目。
 *   判据：老师读完之后能不能感觉到平台变了。
 * - 🔴 **正文里不许留 Markdown 星号**（`**…**`）：这一屏是纯文本渲染，
 *   星号会原样显示成字面星号。要强调就用短句本身。
 * - 🔴 **`at` 要写全年**（2026-10-04 用户要求"多久出的应用版也写进去"）：
 *   形如 `2026年10月4日`。只写"10月4日"的话，跨年之后这一屏就看不出先后了。
 *   月日之间**不空格**，全表统一。
 * - **最新的在最上面**，第一条的 `v` 必须与 `APP_VERSION` 对得上。
 *   版本之间**不重复**：已经写进上一版的事，不要在下一版里再说一遍。
 * - 🔴 **`at` 的口径（2026-09-25 定，纠了一处真实的矛盾）**：
 *   它 = **这套改动真的落进仓库的那一天**（= 那批提交的 `git log` 日期）。
 *   **不是**"计划发布日"、**不是**"凑整的漂亮数字"、**不是**"下一次发版日"。
 *   反例（已修）：`0.8.0` 原来写 `9 月 26 日`，而它的 15 条改动全部落在
 *   `2026-09-21` / `09-22` 的提交里（版本号本身是 `62fa8da`（2026-09-22）提的），
 *   于是它比后一版 `0.9.0`（`9月25日`）还晚 —— **版本倒挂**，老师看到的时间线是反的。
 *   规矩本身写在 `功能设计与不变量.md` §一 · 1.1「日期口径」。
 *   ⚠️ **没有确切的发版日就不要编**：写 `待定`，等真发版那天再填。
 */

/**
 * 更新日志的一条。
 *
 * 🔴 `only` = **只在一端成立的那句话**（2026-10-04 加，扫「exe 与 apk 文案有没有分开」时发现）。
 *
 * 背景：`items` 原来是 `string[]`，**两端逐字同一条** —— 于是
 * 「桌面版自带一个备份文件夹：装上就每 5 分钟自动写一份…」在**教师端 apk 上照显**，
 * 而 apk 根本没有那个文件夹（`hasBuiltinBackupDir` 在 WebView 里恒 false）。
 * 老师照着做、找不到那张备份卡片 —— **一句只在桌面成立的承诺，写在了手机上**。
 *
 * 两档的准确含义（**别记反，也别自己引申出第三档**）：
 *
 * | 值 | 谁能看到 | 判据 |
 * |---|---|---|
 * | `'desktop'` | **只**两个 exe | `shellPlatform() === 'electron'` |
 * | `'mobile'`  | apk **和**网页版 | `shellPlatform() !== 'electron'` |
 *
 * ⚠️ **网页版归在 `'mobile'` 那一档** —— 别写成"apk 才能看到"：
 *   网页版的手机流量和 apk 走的是同一套界面，它照样有移动端导航。
 *
 * ⚠️ **不给 `'desktop'` 打标就是两端都显示**（默认值）——
 *   凡是两端都成立的句子（例：「点「就地打开」失败时会说清楚」）
 *   **一个标都不许打**。打了反而把一句对的话切成两半。
 *   ⚠️ 而**一条里混着两端的事**时必须拆成两条（标是整条生效的）。
 */
export type ChangeLogItem = string | { text: string; only?: 'desktop' | 'mobile' }

export type ChangeLogEntry = {
  /** 版本号（与 `lib/version.ts` 的 `APP_VERSION` 一致） */
  v: string
  /** 发版日，例：`2026年10月4日`；还没定就写 `待定`（别编） */
  at: string
  items: ChangeLogItem[]
}

