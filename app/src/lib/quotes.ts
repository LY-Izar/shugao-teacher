/** 按天取一句：**同一天固定**（用北京时间的日期做种子，不用随机 —— 否则刷新一次就换一句） */
export function pickDailyQuote(d = new Date()): DailyQuote {
  const i = ((dayIndex(d) % DAILY_QUOTES.length) + DAILY_QUOTES.length) % DAILY_QUOTES.length
  return DAILY_QUOTES[i]
}
