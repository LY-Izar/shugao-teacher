/* ============================================================
   化学知识树 —— **人教版**（高一必修 / 高二选择性必修 / 高三复习）
   ------------------------------------------------------------
   为什么要有这棵树：错题集要回答的是「他在哪个知识点上掉分最多」，
   而不是「他错了第 3 题」。没有知识点维度，统计只是一堆题号。

   为什么用关键词匹配而不是再调一次 AI：
     · 一次导入几十道题，逐题调模型既慢又花钱
     · 化学题的关键词辨识度极高（「盐类水解」「勒夏特列原理」「阿伏加德罗常数」
       几乎不会出现在别的章节）
     · **完全本机、零成本、可离线**，符合「AI 是加速器不是必经环节」
   匹配不上的题会落到「未归类」，教师不需要管 —— 有总比没有好，
   而且后续可以再叠加人工修正。

   ------------------------------------------------------------
   组织方式（照 `physics.ts` / `types.ts` 的约定）：

     学科 → 教材（年级 + 版本） → 章节 → 知识点

   化学这里 **一本教材一段，一共 6 本**，顺序就是界面顺序：

     高一 · 人教版 必修第一册   （第一章 ~ 第四章）
     高一 · 人教版 必修第二册   （第五章 ~ 第八章，章号是人教版全六册连排）
     高二 · 人教版 选择性必修1 化学反应原理   （第一章 ~ 第四章）
     高二 · 人教版 选择性必修2 物质结构与性质 （第一章 ~ 第三章）
     高二 · 人教版 选择性必修3 有机化学基础   （第一章 ~ 第五章）
     高三 · 人教版 一轮复习     （专题一 ~ 专题十二，**复习体系不是教材分册**）

   ⚠️ **章号为什么从「第五章」起**：人教版 2019 的必修两册是**连排章号**
      （必修第一册 1~4 章，必修第二册 5~8 章），所以 `chem-ch-g1-b2-c5`
      指的是「第五章」而不是「第二册第一章」。这样老师对着课本目录找得到。
      选择性必修三本是各自从第一章起，与教材一致。

   ⚠️ **高三那一本是"一轮复习专题"，不是出版社的教材**：
      高三化学没有第七、第八册，全国都用复习资料，所以这本的 `chapters`
      是**校本复习体系**（专题一~十二），`version` 如实写「一轮复习」。
      它和四本教材之间有**必然的知识点重叠**（同一考点在教材里一个 id、
      在复习体系里另一个 id）。这是刻意的：
        · 高一的题归到教材知识点，老师按课本目录看；
        · 高三的题归到复习专题，老师按复习进度看；
      两套视图各自的统计都自洽，不做跨册去重（去重会让高三的统计
      把「复习专题」拆散到六本教材里，反而看不出复习进度）。

   ⚠️ **id 规则（全文件自洽，别改成别的写法）**：
      章节 id = `chem-ch-<年级>-<册>-c<章号>`  例：`chem-ch-g1-b1-c2`
      知识点 id = `chem-g<年级>-<册>-c<章号>-p<序号>`  例：`chem-g1-b1-c2-p3`
      高三复习：册位固定写 `r1`（第一轮），例：`chem-g3-r1-c5-p2`
      **一律小写英文 + 连字符，不许出现中文**（id 要进数据库、要拼进 URL）。
      前缀 `chem-` 不是装饰：`QuestionMeta.points` 存的是**裸 id**，
      全局表（`POINT_NAME` / `POINT_CHAPTER`）按 id 合并所有学科，
      两科各写一个同名 id（比如 `energy`）就会**互相覆盖且不报错**。
      详见 `types.ts` 头上的 `ID_PREFIXES`。

   ⚠️ 关键词只写**"题目里真会出现、而且别科不会出现"**的词：
      写「物质的量浓度」「酯化反应」「勒夏特列原理」，
      别写「反应」「溶液」「正确」这种满篇都是的词 —— 词越通用，
      打标越像没打。`lib/knowledge.ts` 的 `tagIn` 按**词长**加权，
      所以长词（「阿伏加德罗常数」）自然压过短词（「摩尔」）。

   ⚠️ **同一个词在"教材"与"高三复习专题"里各出现一次，是刻意留的**：
      化学是螺旋上升的，一个考点在必修、选择性必修、一轮复习里都讲，
      所以「盖斯定律」「勒夏特列原理」「吸氧腐蚀」这类词会同时出现在
      两本书的关键词表里（已实测：**同一年级内部零重复**，
      跨年级的复用还有 37 个）。后果只有一个，如实写在这里：
        · `tagQuestionIn(text, { subject: 'chemistry', grade: '高一' })`
          —— 只扫高一两本，**不受影响**；
        · `tagQuestionIn(text, { subject: 'chemistry' })`（不传 grade）
          —— 会把同一段文字按教材知识点和复习专题**各打一次**，
          排名不受影响（两边加分相同），只是 `MAX_POINTS` 取前三时
          可能被同义的两个标签占掉两个名额。
      不进一步"消歧"的原因：教材视图与复习视图本来就该各自完整，
      把复习专题的词删空只会让高三那棵树的打标退化成「未归类」。
      真要跨年级混着打标，调用方按年级分开调即可（见 `TagOptions.grade`）。
   ============================================================ */

