/* ============================================================
   历史知识树 —— **人教版（统编版）**，覆盖高一 → 高三
   ------------------------------------------------------------
   为什么要有这棵树：历史错题最典型的失分不是"这题不会"，而是
   "这次改革 / 这套制度 / 这个条约我记混了" —— 错题集要按
   **事件、制度、条约、人物、阶段特征**聚类，只存题号等于没统计。

   为什么用关键词匹配而不是再调一次 AI：
     · 一次导入几十道题，逐题调模型既慢又花钱；
     · 历史题的关键词辨识度极高（「军机处」「《辛丑条约》」「青苗法」
       「威斯特伐利亚和约」几乎不会出现在别的知识点上），
       而人名、朝代名、制度名、条约名恰好是题面上一定会出现的；
     · **完全本机、零成本、可离线**，符合「AI 是加速器不是必经环节」。
   匹配不上的题落到「未归类」，教师不用管 —— 有总比没有好，
   而且后续可以叠加人工修正（本文件就是人工修正要对照的那张表）。

   ------------------------------------------------------------
   🔴 **id 规则（自洽、稳定、不含中文）** —— 与 `physics.ts` 同一套

     章节：`his-g<年级号>-c<章号>`     例 `his-g1-c1`（高一必修上第 1 单元）
     高三复习专题：`his-g3-t<专题号>`  例 `his-g3-t1`
     知识点：`<章节 id>-p<序号>`       例 `his-g1-c1-p3`

     章号**跨册连续**（与物理的必修一→二→三连号一致）：
     高一两册 = `his-g1-c1` … `his-g1-c20`；
     高二三册各自从 1 开始（年级号已经把两册隔开了）：
     选必 1 = `his-g2-c1` … `his-g2-c6`，选必 2 = `his-g2-c7` … `his-g2-c12`，
     选必 3 = `his-g2-c13` … `his-g2-c18`。
     序号按书写顺序从 1 递增，**只增不改** —— 已经写进历史错题的 id
     一旦改名，那些题就全变成「未归类」。

   ⚠️ **前缀 `his-` 必须带**：`QuestionMeta.points` 存的是**裸 id**，
      而 `POINT_NAME` / `POINT_CHAPTER` 是**跨学科全局表**，
      两科撞一个同名 id 会互相覆盖而且**不报错**（见 `types.ts`）。

   ------------------------------------------------------------
   ⚠️ **年级与册次的组织方式（刻意如此，别"优化"）**

     高一 → '人教版·中外历史纲要（上）' / '人教版·中外历史纲要（下）'
     高二 → '人教版·选择性必修1 国家制度与社会治理'
            '人教版·选择性必修2 经济与社会生活'
            '人教版·选择性必修3 文化交流与传播'
     高三 → '人教版·高考总复习'

     ⚠️ **"必修两册归高一、选择性必修三册归高二"是常见教学安排，
        不是教材规定**：统编版官方只分"必修 / 选择性必修"，没规定
        哪一册在高几上。本校按"高一必修两册、高二选必三册"排；
        别的学校把《纲要下》挪到高一下、选必提前，改的只是 `grade`
        这一个字段，**章节一个字都不用动**。

   ⚠️ **高三那本是「一轮/二轮复习专题」，不是第六本教材**：
     复习专题**故意与高一高二基本不重叠** —— 那些章节已经逐一列过
     具体知识点，复习树只收**跨册的阶段特征、史学素养与题型方法**
     （「史料实证」「二重证据法」「开放性小论文」「中外关联比较」…）。
     这样有两个好处：① 总点数不翻倍；② 打标时关键词不打架 ——
     否则「中央集权」这种词会同时命中七八个点，等于没打。

   ⚠️ **关键词只写"题面上真会出现、而且别处不会出现"的词**：
     人名、朝代名、制度名、条约名、文献名、地名最好用；
     写「改革」「战争」「原因」「影响」「历史」这种满篇都有的词，
     打标结果就是噪声。**书名号不要写进关键词** —— 写 `史记`
     才能同时命中「史记」和「《史记》」。词越长越具体，权重越高
     （`lib/knowledge.ts` 的 `tagIn`：`score += 关键词长度`，取前 3 个）。

   ⚠️ **《纲要》与选必在"制度史"上有真重叠，这是教材本身的重叠，
      不是这里写错了**：《纲要上》第 7 课与选必 1 第 1 课都讲三省六部制，
     第 15 课与选必 1 第 16 课都讲赋税制度，"察举制""行省制"这类词也是
     两本书都讲。**同一个词落在两个点上，打标只会多一个标签，不会报错。**
     处理办法不是把词删掉（删了高一那道题就没人认领了），而是：
       ① 用 `tagQuestionIn(text, { subject: 'history', grade: '高一' })`
          按年级收窄 —— 导入作业时本来就知道年级，**推荐这条**；
       ② 或让老师人工改（本表就是给人工改的）。
     本文件已经尽量让两本书的用词错开（一个词尽量只在一本书里当关键词，
     另一本改用相邻的具体词），但**没有做到零重叠**。

   ------------------------------------------------------------
   📌 **章节名（单元名）的可信度（诚实说明，别当"官方目录"引用）**
     · 单元名与单元数是对着教材目录核过的，不是凭印象编的：
       高一必修上 11 单元 30 课 / 必修下 9 单元 23 课 /
       选必 1 六单元 18 课 / 选必 2 六单元 15 课 / 选必 3 六单元 15 课。
       核对来源是备课站按册分单元、按课列出的成套目录
       （菁优网备课中心「人教版（新教材）」中外历史纲要（上/下）、
       选择性必修 1/2/3 的目录树），见本文件末尾注。
     · ⚠️ **知识点名不是教材的"课标题"**，而是把一课拆成"能挂一道题上去"
       的粒度（第 5 课拆成"东晋南朝的门阀政治""北魏孝文帝改革"…）。
       **章节名才是目录，知识点名是给打标用的**。
     · ⚠️ **单元名在不同印次之间有细微差异**：如第二单元有的印次写作
       "…与隋唐大一统的发展"，本文件用较完整的"…与隋唐统一多民族
       封建国家的发展"；《纲要上》2023 年修订新增第十一单元
       "中国特色社会主义新时代"，本文件已收录，但**新增两课的课号
       在不同印次里有不同说法，所以本文件的知识点名一律不带课号**。
     · ⚠️ **高三整册没有官方教材目录**，`his-g3-t*` 的八个专题是按
       **一轮复习的通行做法 + 高考题型**整理的，属**工程约定**，
       不是任何一本教材的目录。
     ============================================================ */

