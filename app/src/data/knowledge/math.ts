/* ============================================================
   数学知识树 —— **人教A版（2019 版新教材）**，覆盖高一 → 高三
   ------------------------------------------------------------
   为什么要有这棵树：错题集要回答的是「他在哪个知识点上掉分最多」，
   而不是「他错了第 3 题」。数学尤其需要这个维度 —— 数学的失分
   是**按题型/方法聚类**的（「恒成立」不会做，往往是导数、数列、
   不等式三处一起掉），只存题号等于没统计。

   为什么用关键词匹配而不是再调一次 AI：
     · 一次导入几十道题，逐题调模型既慢又花钱；
     · 数学的题干有相当强的术语辨识度（「错位相减」「二面角」
       「离心率」「恒成立」「零点个数」几乎不会出现在别的知识点）；
     · **完全本机、零成本、可离线**，符合「AI 是加速器不是必经环节」。
   匹配不上的题会落到「未归类」，教师不需要管 —— 有总比没有好，
   而且后续可以再叠加人工修正。

   ------------------------------------------------------------
   🔴 **id 规则（自洽、稳定、不含中文）**

     章节：`mat-g<年级号>-c<章号>`        例 `mat-g1-c1`（高一必修一第 1 章）
     高三复习专题：`mat-g3-t<专题号>`     例 `mat-g3-t1`
     知识点：`<章节 id>-p<序号>`          例 `mat-g1-c1-p3`

     `mat-` 前缀**必须带**（见 `types.ts` 的 `ID_PREFIXES`）：
     `QuestionMeta.points` 存的是**裸 id**，`POINT_NAME` / `POINT_CHAPTER`
     是**跨学科全局表**，两科各写一个同名 id 会互相覆盖而且**不报错**。
     序号按书写顺序从 1 递增，**只增不改** —— 已经写进历史错题的 id
     一旦改名，那些题就全变成「未归类」。

   ------------------------------------------------------------
   ⚠️ **年级与册次的组织方式（刻意如此，别"优化"）**

     一门课一个文件，文件里是**若干本教材**，一本教材一段。
     数学的人教A版是 5 本书 + 一个复习专题，所以高一段会看到
     **两本**、高二段会看到 **三本**，`version` 是用来分辨册次的：

       高一 → '人教A版·必修第一册' / '人教A版·必修第二册'
       高二 → '人教A版·选择性必修第一册' / 第二册 / 第三册
       高三 → '人教A版·高考总复习'

     为什么不用 `version: '人教A版'` 一套到底：
     `version` 在这一层是**唯一能分辨册次的地方**（`Textbook` 只有
     grade / version / chapters 三个字段），五本书写同一个 version
     在按版本过滤（`textbooksOf('math', '高一', '人教A版')`）时会
     互相吞掉，老师界面上也分不出"必修一"和"必修二"。

   ⚠️ **高三那本是「一轮/二轮复习专题」，不是第六本教材**：
     复习专题**故意与高一高二不重叠** —— 那些章节已经逐一列过具体
     知识点了，复习树只收**跨章节的综合题型、新高考新题型与解题策略**
     （「恒成立」「零点个数」「结构不良」「新定义」…）。
     这样有两个好处：① 总点数不翻倍；② 打标时关键词不打架 ——
     否则「导数」这种词会同时命中七八个点，等于没打。

   ⚠️ 关键词只写"**题面上真会出现、而且别处不会出现**"的词：
     写「计算」「函数」「求解」这种满篇都有的词，打标结果就是噪声。
     词越长越具体，权重越高（见 `lib/knowledge.ts` 的 `tagIn`）。
   ============================================================ */

