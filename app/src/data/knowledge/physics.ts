/* ============================================================
   物理知识树 —— **教科版（2019 版新教材）**，覆盖高一 → 高三
   ------------------------------------------------------------
   为什么要有这棵树：错题集要回答的是「他在哪个知识点上掉分最多」，
   而不是「他错了第 3 题」。物理的失分更是**按模型聚类的** ——
   「传送带」「板块」「带电粒子偏转」「双杆切割」各自是一类题，
   只存题号等于没统计。

   为什么用关键词匹配而不是再调一次 AI：
     · 一次导入几十道题，逐题调模型既慢又花钱；
     · 物理题的关键词辨识度极高（「等势面」「安培力」「光电效应」
       「回旋加速器」几乎不会出现在别的章节）；
     · **完全本机、零成本、可离线**，符合「AI 是加速器不是必经环节」。
   匹配不上的题会落到「未归类」，教师不需要管 —— 有总比没有好，
   而且后续可以再叠加人工修正。

   ------------------------------------------------------------
   🔴 **id 规则（自洽、稳定、不含中文）**

     章节：`phy-g<年级号>-c<章号>`      例 `phy-g1-c1`（高一必修第一册第 1 章）
     高三复习专题：`phy-g3-t<专题号>`   例 `phy-g3-t1`
     知识点：`<章节 id>-p<序号>`        例 `phy-g1-c1-p3`

     序号按书写顺序从 1 递增，**只增不改** —— 已经写进历史错题的 id
     一旦改名，那些题就全变成「未归类」。

   ⚠️ **前缀这件事，本科内部是混着的，这是刻意的，别"统一"**：
     · **旧树（`PHY_LEGACY`）里那 18 个裸 id**（`coulomb` / `ohm` /
       `energy` …）是搬家前就有的，已经写进历史档案，**一个字都不能改**；
     · **本次新增的点一律带 `phy-` 前缀**（见 `types.ts` 的 `ID_PREFIXES`：
       `QuestionMeta.points` 存的是**裸 id**，而 `POINT_NAME` /
       `POINT_CHAPTER` 是**跨学科全局表**，两科撞一个同名 id 会互相覆盖
       而且**不报错**）。`grep -r "phy-" app/src` 在本文件之前**零命中**，
       所以 `phy-` 这一片命名空间是物理独占的。
     · 新旧点的对应关系写在**各章顶部的注释**里（例：`phy-g1-c1-p2`
       对应旧 id `newton`），这是给「人工改知识点」时看的线索，
       不是运行时映射 —— 代码里不写映射表。

   ------------------------------------------------------------
   ⚠️ **年级与册次的组织方式（刻意如此，别"优化"）**

     一门课一个文件，文件里是**若干本教材**，一本教材一段。
     物理教科版是 6 本书 + 一个复习专题，所以高一段会看到**三本**、
     高二段会看到**三本**，`version` 是唯一能分辨册次的地方
     （`Textbook` 只有 grade / version / chapters 三个字段）：

       高一 → '教科版·必修第一册' / '教科版·必修第二册' / '教科版·必修第三册'
       高二 → '教科版·选择性必修第一册' / 第二册 / 第三册
       高三 → '教科版·高考总复习'

     ⚠️ **"必修三册归高一、选择性必修三册归高二"是常见教学安排，
        不是教材规定**：教科版官方只按"必修 / 选择性必修"分册，
        没有规定哪一册在高几上。本校按"高一三册、高二三册"排；
        别的学校把必修三放到高二、把选择性必修一放到高二下，
        改的是 `grade` 这一个字段，**章节一个字都不用动**。

   ⚠️ **高三那本是「一轮/二轮复习专题」，不是第七本教材**：
     复习专题**故意与高一高二不重叠** —— 那些章节已经逐一列过具体
     知识点了，复习树只收**跨章节的综合题型、模型与新高考题型**
     （「板块模型」「双杆切割」「有效值」「图像斜率面积」…）。
     这样有两个好处：① 总点数不翻倍；② 打标时关键词不打架 ——
     否则「受力分析」这种词会同时命中七八个点，等于没打。

   ⚠️ **关键词只写"题面上真会出现、而且别处不会出现"的词**：
     写「计算」「分析」「物理」「求解」这种满篇都有的词，
     打标结果就是噪声。词越长越具体，权重越高（见 `lib/knowledge.ts`
     的 `tagIn`）。同一科内也要避免一个词落在两个点上（撞了就按
     词长与书写顺序决定，等于随机）。

   ------------------------------------------------------------
   📌 **章节名与节名的可信度（诚实说明，别当"官方目录"引用）**
     下面每一章的"章名 + 节名"是照着教科版（2019）**教材的实际章节
     结构**抄的（核对过教科社配套资源与教辅的目录逐节列表，见
     `zxxk.com` / `21cnjy.com` 的教科版成套资源目录），**不是编的**；
     但以下三处是**按常识推的**，用前请对一眼手边教材：
       ① 每章**节号**（1.x / 2.x）在教辅目录里是连续可核的，
          但个别"选学"节（如 5.1 斜抛运动、5.2/5.3 相对论与宇宙）
          是否单独成节、是否计入课时，各校处理不同；
       ② **高三总复习**没有官方教材目录，`phy-g3-t*` 的分法是按
          高考题型/模型整理的，属**工程约定**；
       ③ 个别节的**归章**（如"静电的利用和防护"在教科版是 1.7 小节，
          人教版把它并进别处）以教科版为准，跨版本出题会略有错位。
     ============================================================ */

