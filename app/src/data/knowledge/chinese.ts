/* ============================================================
   语文知识树 —— **人教版**（高中统编版，2019 年秋起全国使用的那一套）
   ------------------------------------------------------------
   为什么语文的章节要按**教材单元**分，而不是按「文言文 / 现代文 / 作文」分：
     · 语文的真问题是「同一道题该挂哪儿」。若章是「现代文阅读」，
       一学期几十道题全落进同一个桶，统计就退化成"一堆题号"。
     · 教材单元是**真实的教学进度**，老师说得出"我讲到第三单元了"，
       说不出"我讲到'现代文阅读'了"。错题按单元归因，才能对上他这周在讲什么。
     · 单元名照**统编版单元名**写（"青春的价值""生命的诗意"），不是自己编的词。
     · 单元内的人文主题各组一篇，知识点则是**可挂题的能力点**
       （"新诗意象的选择与组合""〈劝学〉的比喻论证"这种粒度，不是"诗歌"这种大词）。

   五册书 = 高一 2 册（必修上/下）+ 高二 3 册（选择性必修上/中/下）：
     · 必修上 / 必修下           → grade: '高一'，各 8 个单元（含整本书阅读、词语/家乡文化）
     · 选择性必修上 / 中 / 下     → grade: '高二'，各 4 个单元（外加"古诗词诵读"）
   高三**没有新教材**，所以高三这一本写的是**高考一轮复习专题**
   （文言文 / 古诗鉴赏 / 现代文阅读 / 语言文字运用 / 写作五大块），
   这是通行做法，也是老师实际在上的东西；它没有单元、只有专题。

   ⚠️ `古诗词诵读` 是每册书末尾的独立板块（不是单元），统编版就是这么排的。
      它单独成章，`version` 里注明了是哪一本的诵读。

   ⚠️ 教材名用的是统编版（部编版）的**书名与单元名**，逐条抄自人教版官方课文目录；
      2019 年之前那套「必修一～必修五」已经退役，这里**不写**。

   ⚠️ 关键词是**用来打哪些题属于这个知识点**的：写"题目里真的会出现"的词
      （「通感」「词类活用」「颔联」），别写「阅读」「赏析」这种满篇都是的词
      —— 词越通用，打标越像没打。参考 `physics.ts`。

   ⚠️ id 一律带 `chn-` 前缀（见 `types.ts` 的 `ID_PREFIXES`）：
      `QuestionMeta.points` 存的是裸 id，两科各写一个同名 id 会**互相覆盖且不报错**。
   ============================================================ */

