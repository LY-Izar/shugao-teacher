/* ============================================================
   政治（思想政治）知识树 —— **人教版（统编版 2019）**，覆盖高一 → 高三
   ------------------------------------------------------------
   这棵树要回答的是「他在哪个知识点上掉分最多」，而不是「他错了第 3 题」。
   政治的主观题失分**比理科更依赖"答到哪个知识点上"** ——
   「矛盾的特殊性」「人民代表大会制度」「违约与违约责任」各自是一类题，
   只存题号，错题集就退化成"一堆题号"，一点归因价值都没有。

   为什么用关键词打标而不是导入时再调一次 AI：
     · 一次导入几十道题，逐题调模型既慢又花钱；
     · 政治题的**教材术语**辨识度极高（「矛盾的普遍性」「基层群众自治」
       「经济全球化」「演绎推理」几乎不会出现在别的模块）；
     · 完全本机、零成本、可离线 —— AI 是加速器，不是必经环节。
   打标打不准的题会落到「未归类」，教师不需要管；后续可叠加人工改知识点。

   ------------------------------------------------------------
   🔴 **id 规则（自洽、稳定、不含中文）**

     章节：`pol-g<年级号>-c<册序号>`      例 `pol-g2-c1`（高二第 1 册：必修3）
     高三复习专题：`pol-g3-t<专题号>`     例 `pol-g3-t4`
     知识点：`<章节 id>-p<序号>`          例 `pol-g2-c4-p4`

     序号按书写顺序从 1 递增，**只增不改**：已经写进历史错题的 id 一旦改名，
     那些题全部变成「未归类」。**新增知识点一律追加在章末**，不要插队重排。

     ⚠️ `pol-g<年级号>-c<册序号>` 里的「册序号」是**这一科教材的书写顺序**
        （高一 1-4、高二 1-7、高三用 t*），**不是**课本封面上那个"必修3"
        —— 课本编号写在每段教材的 `version` 里（`人教版·必修3`）。
        两者不是一回事，别混。

     ⚠️ 本科所有 id 都带 `pol-` 前缀（见 `types.ts` 的 `ID_PREFIXES`）：
        `QuestionMeta.points` 存的是**裸 id**，而 `POINT_NAME` /
        `POINT_CHAPTER` 是**跨学科全局表**，两科撞一个同名 id 会互相覆盖
        而且**不报错**。物理那批裸 id 是历史例外，政治不是。

   ------------------------------------------------------------
   ⚠️ **年级与册次的组织方式（刻意如此，别"优化"）**

     一门课一个文件，文件里是**若干本教材**，一本教材一段。
     统编版高中思想政治一共 7 本书，本校按「高一 4 本、高二 3 本」排：

       高一 → 人教版·必修1 中国特色社会主义 / 必修2 经济与社会
       高二 → 人教版·必修3 政治与法治 / 必修4 哲学与文化
              / 选择性必修1 当代国际政治与经济
              / 选择性必修2 法律与生活 / 选择性必修3 逻辑与思维
       高三 → 人教版·高考总复习（专题，不是第八本书）

     ⚠️ **"必修3/必修4 放在高二"是常见教学安排，不是教材规定**：
        统编版官方只按"必修 / 选择性必修"分册，**没有规定哪一册在高几上**。
        有的学校把必修3、必修4 放在高一下学期（高二直接开选择性必修），
        有的学校把必修1 放在高一上、必修2 放在高一下。改的是 `grade`
        这一个字段，**章节一个字都不用动**。

     ⚠️ **必修4《哲学与文化》是文理分科后最重的一本**（哲学部分是高考
        主观题的主战场），所以它单独占 `pol-g2-c2` 一整册的位置，
        内部按"唯物论 / 认识论 / 辩证法 / 历史唯物主义 / 文化"五章拆开 ——
        拆成章是为了让界面按单元分组时**跟课本目录对得上**。

   ------------------------------------------------------------
   ⚠️ **关键词只写"题面上真会出现、而且本科别处不会出现"的词**

     写「分析」「说明」「体现」「意义」「措施」这种满篇都有的词，
     打标结果就是噪声（那属于题型，不是知识点）。词越长越具体，权重越高
     （见 `lib/knowledge.ts` 的 `tagIn`）。**同一科内也要避免一个词落在
     两个点上** —— 撞了就按词长与书写顺序决定，等于随机。

     政治特有的坑：**时政词跨模块**（「高质量发展」既可能是必修2 的
     经济发展，也可能是选必1 的经济全球化；「法治」既可能是必修3 的
     全面依法治国，也可能是选必2 的纠纷解决）。处理办法：
       · 每个点优先写**教材术语**（「矛盾的普遍性」「违约责任」「联合国」），
         而不是时政口号；
       · 跨模块真会重的词，**只挂在主场那个点上**，别的点换一个更专的说法。

   ------------------------------------------------------------
   ⚠️ **高三那本是「一轮/二轮复习专题」，不是第八本教材**

     复习专题**故意与高一高二不重叠** —— 那些知识点已经逐条列过了，
     复习树只收**跨模块的综合题型、时政热点专题与新高考题型**
     （「评析类」「意义类」「措施类」…）。这样有两个好处：
     ① 总点数不翻倍；② 打标时关键词不打架 —— 否则「党的领导」这种词
     会同时命中七八个点，等于没打。

   ------------------------------------------------------------
   📌 **教材目录我有多确定（诚实说明，别当"官方目录"引用）**

     · **确知**：7 本书的**书名、单元划分、课号与课题名**。这是统编版
       （2019 课标）教材的公开目录，我按"单元 → 课 → 框题"的层级核对过
       （交叉核对过教辅与课件资源的目录页，例如
       [必修3 课件资源目录](https://m.zxxk.com/docpack/3403354.html)、
       [必修4 第三单元第九课](https://www.zxxk.com/soft/58920805.html)、
       [选必1 第九课 中国与国际组织](https://beikeyi.cn/beike_2jgLVAm6Nz.html)、
       [选必2 第九课 纠纷的多元解决方式](https://beikeyi.cn/beike_ajlk360A9Y.html)）。
     · **确知**：`pol-` 下每个知识点的**名称**都是教材里的原话术语，
       不是我造的词。
     · **凭常识推的三处**（用前请对一眼手边教材，改起来只动 `name`）：
       ① **框题级的归组**：我是按"一个框题 = 一个知识点"的粒度列的，
          个别框题内容特别多（如必修4「矛盾是事物发展的源泉和动力」）
          我拆成了 2-3 个点，**拆法是我的工程判断，不是教材结构**；
       ② **高三总复习没有官方教材目录**，`pol-g3-t1..t7` 的七个专题
          是按**高考模块 + 时政热点**整理的工程约定，不是任何一本书的目录；
       ③ 个别**课号**（尤其选必2、选必3 的第二、三单元）我按新教材
          修订后的课序写的，若你手上是更早的印次，课号可能差一位
          —— 结构不变，只影响 `name` 里的"第X课"三个字。
     ============================================================ */

